// Bakes the typing for the hero video: every keystroke of the sentence, typed on a
// Russian keyboard, run through the real KazType engine (the web demo's WebAssembly
// build), with the time it lands. Writes assets/typing.js for index.html.
//   node scripts/bake-typing.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const web = path.resolve(here, "../../../web")
const out = path.resolve(here, "../assets/typing.js")

export const TYPED = "Салем! Жексенби куни тауга барамыз, сендер де келиндер"
const START = 0.5 // first key
const END = 13.4 // last key
const WORD_HOLD = 0.42 // pause before a word is committed, so its candidates read
const CANDIDATES = 3

const { default: create } = await import(path.join(web, "src/wasm/kaz.js"))
const mod = await create({
  instantiateWasm: (imports, ok) => {
    WebAssembly.instantiate(fs.readFileSync(path.join(web, "src/wasm/kaz.wasm")), imports).then((r) => ok(r.instance, r.module))
    return {}
  },
})
mod.FS.writeFile("/kaztype.bin", fs.readFileSync(path.join(web, "public/kaztype.bin")))
if (!mod.cwrap("kaz_load", "number", ["string"])("/kaztype.bin")) throw new Error("model failed to load")
const convert = mod.cwrap("kaz_convert", "string", ["string", "string", "number"])
const candidatesFor = (typed, context) => convert(typed, context, CANDIDATES).split("\n").slice(0, -1)

const isLetter = (c) => /^[Ѐ-ӿ]$/.test(c) && c.toLowerCase() !== c.toUpperCase()

// Seeded jitter so key rhythm looks human but every bake is identical.
let seed = 7
const rand = () => {
  seed |= 0
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}

// Relative gaps first, then scaled so the last key lands at END.
const gaps = []
for (let i = 0; i < TYPED.length; i++) {
  const c = TYPED[i]
  let g = 1 + (rand() - 0.5) * 0.5
  if (!isLetter(c) && i > 0 && isLetter(TYPED[i - 1])) g += WORD_HOLD / 0.18
  gaps.push(i === 0 ? 0 : g)
}
const total = gaps.reduce((a, b) => a + b, 0)
const unit = (END - START) / total

let text = ""
let typed = ""
let context = ""
let t = START
const keys = []
for (let i = 0; i < TYPED.length; i++) {
  t += gaps[i] * unit
  const c = TYPED[i]
  if (isLetter(c)) {
    if (!typed) context = text.slice(-64)
    typed += c
    keys.push({ t: +t.toFixed(3), key: c, text, typed, candidates: candidatesFor(typed, context) })
  } else {
    if (typed) text += candidatesFor(typed, context)[0]
    typed = ""
    text += c
    keys.push({ t: +t.toFixed(3), key: c, text, typed: "", candidates: [] })
  }
}
if (typed) text += candidatesFor(typed, context)[0]
keys.push({ t: +(END + 0.35).toFixed(3), key: "", text, typed: "", candidates: [] })

fs.writeFileSync(
  out,
  `// Generated by scripts/bake-typing.mjs from the KazType engine. Do not edit.\nwindow.KAZ_TYPING = ${JSON.stringify({ typed: TYPED, result: text, keys })};\n`,
)
console.log(`${keys.length} keys, ${START}s to ${END}s`)
console.log(TYPED)
console.log(text)
